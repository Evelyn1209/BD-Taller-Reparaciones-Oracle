-- VIEW TO LIST WORK ORDERS
CREATE OR REPLACE VIEW VW_WORKORDERS AS
SELECT
    wo.workorder_id,
    wo.opened_at,
    wo.updated_at,
    wo.problem_desc,
    wo.diagnosis,
    wo.labor_cost,
    wo.discount_amt,
    wo.total_amount,
    -- Estado
    ws.status_id,
    ws.name              AS status_name,
    -- Equipo
    e.equipment_id,
    e.brand,
    e.model,
    e.serial_no,
    -- Cliente
    c.customer_id,
    p.full_name          AS customer_name,
    p.identification_number AS customer_id_num,
    -- Categoria
    ec.name              AS category_name,
    -- Responsable: quien creo la orden
    wo.created_by        AS created_by_employee_id,
    pe_c.full_name       AS created_by_name,
    -- Responsable: quien actualizo por ultima vez
    wo.updated_by        AS updated_by_employee_id,
    pe_u.full_name       AS updated_by_name
FROM TBL_WORKORDERS_P wo
JOIN TBL_WORKORDER_STATUS   ws   ON ws.status_id    = wo.status_id
JOIN TBL_EQUIPMENT          e    ON e.equipment_id  = wo.equipment_id
JOIN TBL_CUSTOMERS          c    ON c.customer_id   = e.customer_id
JOIN TBL_PERSON             p    ON p.person_id     = c.person_id
JOIN TBL_EQUIPMENT_CATEGORY ec   ON ec.category_id  = e.category_id
LEFT JOIN TBL_EMPLOYEES     emp_c ON emp_c.employee_id = wo.created_by
LEFT JOIN TBL_PERSON        pe_c  ON pe_c.person_id   = emp_c.person_id
LEFT JOIN TBL_EMPLOYEES     emp_u ON emp_u.employee_id = wo.updated_by
LEFT JOIN TBL_PERSON        pe_u  ON pe_u.person_id   = emp_u.person_id;


-- VW_WORKORDER_DETAIL
-- Muestra el encabezado de la orden + cada item (servicio o repuesto)
-- Usa LEFT JOIN en items para que ordenes sin items tambien aparezcan
CREATE OR REPLACE VIEW VW_WORKORDER_DETAIL AS
SELECT
    -- Encabezado de la orden
    wo.workorder_id,
    TO_CHAR(wo.opened_at,  'DD/MM/YYYY HH24:MI') AS opened_at,
    TO_CHAR(wo.updated_at, 'DD/MM/YYYY HH24:MI') AS updated_at,
    wo.problem_desc,
    wo.diagnosis,
    wo.labor_cost,
    wo.discount_amt,
    wo.total_amount,
    ws.name                                       AS status_name,
    -- Responsable de la orden
    pe_c.full_name                                AS created_by_name,
    pe_u.full_name                                AS updated_by_name,
    -- Detalle del item (NULL si la orden no tiene items aun)
    i.item_id,
    i.item_type,
    i.qty,
    i.unit_price,
    (i.qty * i.unit_price)                        AS subtotal,
    CASE
        WHEN i.item_type = 'SERVICE' THEN s.name
        WHEN i.item_type = 'PART'    THEN pt.name
        ELSE NULL
    END                                           AS item_name,
    s.code                                        AS service_code,
    pt.sku                                        AS part_sku
FROM TBL_WORKORDERS_P wo
JOIN  TBL_WORKORDER_STATUS   ws    ON ws.status_id    = wo.status_id
LEFT JOIN TBL_WORKORDER_ITEMS_P i ON i.workorder_id  = wo.workorder_id
LEFT JOIN TBL_SERVICES       s    ON s.service_id    = i.service_id
LEFT JOIN TBL_PARTS          pt   ON pt.part_id      = i.part_id
LEFT JOIN TBL_EMPLOYEES      emp_c ON emp_c.employee_id = wo.created_by
LEFT JOIN TBL_PERSON         pe_c  ON pe_c.person_id   = emp_c.person_id
LEFT JOIN TBL_EMPLOYEES      emp_u ON emp_u.employee_id = wo.updated_by
LEFT JOIN TBL_PERSON         pe_u  ON pe_u.person_id   = emp_u.person_id;

