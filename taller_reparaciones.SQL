    UPDATE TBL_SYS_USERS 
    SET last_login = SYSTIMESTAMP 
    WHERE user_id = p_user_id;
    
    COMMIT;
    DBMS_OUTPUT.PUT_LINE('Bienvenido/a, ' || p_full_name);

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20115, 'Credenciales inválidas. Por favor verifique su usuario y contraseña.');
    WHEN OTHERS THEN
        IF SQLCODE NOT BETWEEN -20999 AND -20000 THEN
            RAISE_APPLICATION_ERROR(-20116, 'Error en el proceso de inicio de sesión: ' || SQLERRM);
        ELSE
            RAISE;
        END IF;
END;
