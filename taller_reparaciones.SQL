CREATE OR REPLACE PROCEDURE SP_UPDATE_WORKORDER (
    p_workorder_id IN TBL_WORKORDERS_P.workorder_id%TYPE,
    p_problem_desc IN TBL_WORKORDERS_P.problem_desc%TYPE,
    p_diagnosis    IN TBL_WORKORDERS_P.diagnosis%TYPE,
    p_labor_cost   IN TBL_WORKORDERS_P.labor_cost%TYPE,
    p_discount_amt IN TBL_WORKORDERS_P.discount_amt%TYPE,
    p_response     OUT NUMBER
) AS
    v_final_labor   TBL_WORKORDERS_P.labor_cost%TYPE;
    v_final_discount TBL_WORKORDERS_P.discount_amt%TYPE;
BEGIN
    -- Leer valores actuales para usarlos en el calculo (antes de modificar la fila)
    BEGIN
        SELECT NVL(labor_cost, 0), NVL(discount_amt, 0)
        INTO v_final_labor, v_final_discount
        FROM TBL_WORKORDERS_P
        WHERE workorder_id = p_workorder_id;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20100, 'No se puede actualizar: La orden de trabajo #' || p_workorder_id || ' no existe.');
    END;

    -- Determinar valores finales (parametro o el actual si no se proporciona)
    v_final_labor   := NVL(p_labor_cost,   v_final_labor);
    v_final_discount := NVL(p_discount_amt, v_final_discount);

    -- Actualizar todos los campos en un solo UPDATE
    UPDATE TBL_WORKORDERS_P
    SET problem_desc = p_problem_desc,
        diagnosis    = p_diagnosis,
        labor_cost   = v_final_labor,
        discount_amt = v_final_discount,
        total_amount = FN_CALC_WORKORDER_TOTAL(p_workorder_id, v_final_labor, v_final_discount)
    WHERE workorder_id = p_workorder_id;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20100, 'No se puede actualizar: La orden de trabajo #' || p_workorder_id || ' no existe.');
    ELSE
        DBMS_OUTPUT.PUT_LINE('Éxito: Orden de trabajo #' || p_workorder_id || ' actualizada correctamente.');
        p_response := 1;
    END IF;

    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        DECLARE
            v_user    VARCHAR2(50) := USER;
            v_code    NUMBER := SQLCODE;
            v_message VARCHAR2(4000) := SQLERRM;
        BEGIN
            INSERT INTO TBL_ERROR_LOG (username, object_name, error_code, error_msg)
            VALUES (v_user, 'SP_UPDATE_WORKORDER', v_code, v_message);
            COMMIT;
        END;
        
        IF SQLCODE NOT BETWEEN -20999 AND -20000 THEN
            RAISE_APPLICATION_ERROR(-20101, 'Error al actualizar la orden de trabajo: ' || SQLERRM);
        ELSE
            RAISE;
        END IF;
END;
/

