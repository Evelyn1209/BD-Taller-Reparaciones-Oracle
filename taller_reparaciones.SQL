-- VISTA MATERIALIZADA - MV_WORKORDERS_SUMMARY
-- Para reportes y dashboard. Refresco ON DEMAND via DBMS_MVIEW.REFRESH.
-------------------------------------------------------------------------------------------------------------------------------------------------------------
CREATE MATERIALIZED VIEW MV_WORKORDERS_SUMMARY
BUILD IMMEDIATE
REFRESH FORCE ON DEMAND
AS
SELECT
    wo.workorder_id,
    TRUNC(wo.opened_at) AS opened_date,
    ws.name          AS status_name,
    p.full_name      AS customer_name,
    e.brand || ' ' || e.model AS equipment_desc,
    e.serial_no,
    ec.name          AS category_name,
    wo.labor_cost,
    wo.discount_amt,
    wo.total_amount,
    COUNT(i.item_id) AS total_items
FROM TBL_WORKORDERS_P wo
JOIN TBL_WORKORDER_STATUS   ws ON ws.status_id   = wo.status_id
JOIN TBL_EQUIPMENT          e  ON e.equipment_id = wo.equipment_id
