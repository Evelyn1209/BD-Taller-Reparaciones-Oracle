-- FN_CALC_WORKORDER_TOTAL
-- Calcula el total de una orden de trabajo.
-- Recibe labor_cost y discount_amt como parametros para evitar ORA-04091:
-- la funcion NO lee TBL_WORKORDERS_P, solo TBL_WORKORDER_ITEMS_P.
-- Formula: labor_cost + SUM(qty * unit_price de items) - discount_amt  (minimo 0)
CREATE OR REPLACE FUNCTION FN_CALC_WORKORDER_TOTAL (
    p_workorder_id IN TBL_WORKORDERS_P.workorder_id%TYPE,
    p_labor_cost   IN TBL_WORKORDERS_P.labor_cost%TYPE,
    p_discount_amt IN TBL_WORKORDERS_P.discount_amt%TYPE
) RETURN NUMBER AS
    v_items_total NUMBER := 0;
BEGIN
    SELECT NVL(SUM(qty * unit_price), 0)
    INTO v_items_total
    FROM TBL_WORKORDER_ITEMS_P
    WHERE workorder_id = p_workorder_id;

    RETURN GREATEST(NVL(p_labor_cost, 0) + v_items_total - NVL(p_discount_amt, 0), 0);
EXCEPTION
    WHEN OTHERS THEN RETURN 0;
END FN_CALC_WORKORDER_TOTAL;
/
