JOIN TBL_EQUIPMENT_CATEGORY ec ON ec.category_id = e.category_id
LEFT JOIN TBL_WORKORDER_ITEMS_P i
       ON i.workorder_id = wo.workorder_id
GROUP BY
    wo.workorder_id,
    TRUNC(wo.opened_at),
    ws.name,
    p.full_name,
    e.brand,
    e.model,
    e.serial_no,
    ec.name,
    wo.labor_cost,
    wo.discount_amt,
    wo.total_amount;



