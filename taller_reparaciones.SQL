-- TRIGGER TRG_WORKORDER_AUDIT_USER
-- BEFORE INSERT: asigna created_by automaticamente desde el usuario Oracle de sesion
-- BEFORE UPDATE: asigna updated_by y updated_at automaticamente
-- Si el usuario de sesion no tiene cuenta de empleado, los campos quedan NULL sin error
CREATE OR REPLACE TRIGGER TRG_WORKORDER_AUDIT_USER
BEFORE INSERT OR UPDATE ON TBL_WORKORDERS_P
FOR EACH ROW
DECLARE
    v_person_id   TBL_PERSON.person_id%TYPE;
    v_employee_id TBL_EMPLOYEES.employee_id%TYPE;
BEGIN
    -- Resolver el employee_id del usuario activo de sesion Oracle
    BEGIN
        SELECT u.person_id INTO v_person_id
        FROM TBL_SYS_USERS u
        WHERE UPPER(u.username) = UPPER(USER);

        SELECT e.employee_id INTO v_employee_id
        FROM TBL_EMPLOYEES e
        WHERE e.person_id = v_person_id;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            v_employee_id := NULL; -- El usuario de sesion no es un empleado registrado
    END;

    IF INSERTING THEN
        -- En INSERT: asignar quien creo la orden
        :NEW.created_by := NVL(:NEW.created_by, v_employee_id);
    ELSIF UPDATING THEN
        -- En UPDATE: registrar quien la modifico y cuando
        :NEW.updated_by := v_employee_id;
        :NEW.updated_at := SYSDATE;
    END IF;
END TRG_WORKORDER_AUDIT_USER;
/

-- TRIGGER TO ENCRIPT USER PASSWORD 
CREATE OR REPLACE TRIGGER TRG_ENCRYPT_USER_PASSWORD
BEFORE INSERT OR UPDATE OF password_hash ON TBL_SYS_USERS
FOR EACH ROW
BEGIN
    -- 1. Verificamos que venga una contraseña
    IF :NEW.password_hash IS NOT NULL THEN
        
        -- 2. Asegurarnos que no sean ya los 64 caracteres de un hash convertido
        IF LENGTH(:NEW.password_hash) <> 64 THEN
            
            -- 3. Lo envolvemos en un SELECT para que el motor SQL procese STANDARD_HASH
            -- sin dar problemas de reconocimiento de variables en PL/SQL
            SELECT RAWTOHEX(STANDARD_HASH(:NEW.password_hash || UPPER(:NEW.username), 'SHA256'))
            INTO :NEW.password_hash
            FROM DUAL;
            
        END IF;
    END IF;
END TRG_ENCRYPT_USER_PASSWORD;
