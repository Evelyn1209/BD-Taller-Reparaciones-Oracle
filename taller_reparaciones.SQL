-- LOGIN USER
CREATE OR REPLACE PROCEDURE SP_LOGIN_USER (
    p_username      IN TBL_SYS_USERS.username%TYPE,
    p_password_hash IN TBL_SYS_USERS.password_hash%TYPE,
    p_user_id       OUT TBL_SYS_USERS.user_id%TYPE,
