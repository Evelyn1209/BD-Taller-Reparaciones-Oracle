-- TBL_PERSON (CREATE IS THE ONLY PART OF THE CRUD THAT WE ARE GOING TO USE IN TBL_PERSON )
CREATE OR REPLACE PROCEDURE SP_SAVE_PERSON (
    p_identification_type_id IN TBL_PERSON.identification_type_id%TYPE,
    p_full_name              IN TBL_PERSON.full_name%TYPE,
    p_identification_number  IN TBL_PERSON.identification_number%TYPE,
    p_status                 IN TBL_PERSON.status%TYPE,
    p_direction              IN TBL_PERSON.direction%TYPE,
    p_contacts               IN ARR_CONTACT,
    p_person_id              OUT TBL_PERSON.person_id%TYPE
)
AS
    v_person_id TBL_PERSON.person_id%TYPE;
BEGIN
    -- Validaciones de campos obligatorios
    IF p_full_name IS NULL OR TRIM(p_full_name) = '' THEN
        RAISE_APPLICATION_ERROR(-20001, 'El nombre completo de la persona no puede estar vacío.');
    END IF;

    IF p_identification_number IS NULL OR TRIM(p_identification_number) = '' THEN
        RAISE_APPLICATION_ERROR(-20002, 'El número de identificación no puede estar vacío.');
    END IF;

    IF p_identification_type_id IS NULL THEN
        RAISE_APPLICATION_ERROR(-20003, 'Debe especificar un tipo de identificación válido.');
    END IF;

    -- Buscar si la persona ya existe por su número de identificación
    v_person_id := FN_GET_PERSON(p_identification_number);

    IF v_person_id = 0 THEN
        -- Insertar nueva persona
        INSERT INTO TBL_PERSON (
            identification_type_id,
            full_name,
            identification_number,
            status,
            direction
        )
        VALUES (
            p_identification_type_id,
            p_full_name,
            p_identification_number,
            p_status,
            p_direction
        )
        RETURNING person_id INTO v_person_id;
        DBMS_OUTPUT.PUT_LINE('Éxito: Datos personales creados para ' || p_full_name);
    ELSE
        -- Actualizar persona existente
        UPDATE TBL_PERSON
        SET identification_type_id = p_identification_type_id,
            full_name              = p_full_name,
            status                 = p_status,
            direction              = p_direction
        WHERE person_id = v_person_id;

        -- Limpiar contactos antiguos para refrescarlos
        DELETE FROM TBL_CONTACT
        WHERE person_id = v_person_id;
        DBMS_OUTPUT.PUT_LINE('Éxito: Datos personales actualizados para ' || p_full_name);
    END IF;

    -- Insertar contactos si se proporcionaron
    IF p_contacts IS NOT NULL THEN
        FOR i IN 1 .. p_contacts.COUNT LOOP
            INSERT INTO TBL_CONTACT (
                person_id,
                method_id,
                contact_value
            )
            VALUES (
                v_person_id,
                p_contacts(i).method_id,
                p_contacts(i).contact_value
            );
        END LOOP;
    END IF;

    p_person_id := v_person_id;
    COMMIT;

EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        DECLARE
            v_user      VARCHAR2(50) := USER;
            v_code      NUMBER := SQLCODE;
            v_message   VARCHAR2(4000) := SQLERRM;
        BEGIN
            INSERT INTO TBL_ERROR_LOG (username, object_name, error_code, error_msg)
            VALUES (v_user, 'SP_SAVE_PERSON', v_code, v_message);
            COMMIT;
        END;

        IF SQLCODE = -2291 THEN
            RAISE_APPLICATION_ERROR(-20004, 'No se puede guardar: El tipo de identificación o un método de contacto no existe en los catálogos.');
        ELSIF SQLCODE NOT BETWEEN -20999 AND -20000 THEN
            RAISE_APPLICATION_ERROR(-20000, 'Error inesperado al guardar datos personales: ' || SQLERRM);
        ELSE
            RAISE;
        END IF;
END;
/
