--FN GET PERSON
CREATE OR REPLACE FUNCTION FN_GET_PERSON (
   p_identification_number IN TBL_PERSON.identification_number%TYPE
) RETURN NUMBER AS
    v_person_id TBL_PERSON.person_id%TYPE;
BEGIN
    SELECT per.person_id
    INTO v_person_id
    FROM TBL_PERSON per
    WHERE per.identification_number = p_identification_number;
    RETURN v_person_id;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN 0;
