-- CREATE WORK ORDER (con array de items en una sola transacción)
CREATE OR REPLACE PROCEDURE SP_CREATE_WORKORDER (
    p_equipment_id IN TBL_WORKORDERS_P.equipment_id%TYPE,
    p_problem_desc IN TBL_WORKORDERS_P.problem_desc%TYPE,
    p_labor_cost   IN TBL_WORKORDERS_P.labor_cost%TYPE,
    p_discount_amt IN TBL_WORKORDERS_P.discount_amt%TYPE,
    p_items        IN ARR_WORKORDER_ITEM,
    p_workorder_id OUT TBL_WORKORDERS_P.workorder_id%TYPE
) AS
    v_status_id    TBL_WORKORDER_STATUS.status_id%TYPE;
    v_items_total  NUMBER := 0;
    v_total        NUMBER := 0;
    v_dummy        NUMBER;
BEGIN
    -- Validaciones de entrada
    IF p_equipment_id IS NULL THEN
        RAISE_APPLICATION_ERROR(-20090, 'Debe especificar el equipo para crear la orden de trabajo.');
    END IF;

    -- Verificar que el equipo existe
    BEGIN
        SELECT 1 INTO v_dummy FROM TBL_EQUIPMENT WHERE equipment_id = p_equipment_id;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20091, 'El equipo con ID ' || p_equipment_id || ' no existe.');
    END;

    IF p_problem_desc IS NULL OR TRIM(p_problem_desc) = '' THEN
        RAISE_APPLICATION_ERROR(-20092, 'La descripción del problema no puede estar vacía.');
    END IF;

    -- Obtener el status inicial (RECIBIDO = display_order 1)
    BEGIN
        SELECT status_id INTO v_status_id
        FROM TBL_WORKORDER_STATUS
        WHERE display_order = 1;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20093, 'No se encontró el estado inicial "RECIBIDO" en la configuración.');
    END;

    -- Insertar la orden
    INSERT INTO TBL_WORKORDERS_P (
        equipment_id, status_id, problem_desc, labor_cost, discount_amt, total_amount
    ) VALUES (
        p_equipment_id, v_status_id, p_problem_desc,
        NVL(p_labor_cost, 0), NVL(p_discount_amt, 0), 0
    )
    RETURNING workorder_id INTO p_workorder_id;

    -- Insertar los ítems y calcular el total
    IF p_items IS NOT NULL AND p_items.COUNT > 0 THEN
        FOR i IN 1 .. p_items.COUNT LOOP
            -- Validar que sea SERVICE o PART
            IF p_items(i).item_type NOT IN ('SERVICE', 'PART') THEN
                RAISE_APPLICATION_ERROR(-20094, 'Tipo de ítem inválido: ' || p_items(i).item_type || '. Solo se permite SERVICE o PART.');
            END IF;
            
            -- Validar coherencia: SERVICE necesita service_id, PART necesita part_id
            IF p_items(i).item_type = 'SERVICE' THEN
                IF p_items(i).service_id IS NULL THEN
                    RAISE_APPLICATION_ERROR(-20095, 'Un ítem de tipo SERVICE debe tener un ID de servicio válido.');
                END IF;
                -- Verificar existencia de servicio
                BEGIN
                    SELECT 1 INTO v_dummy FROM TBL_SERVICES WHERE service_id = p_items(i).service_id;
                EXCEPTION
                    WHEN NO_DATA_FOUND THEN
                        RAISE_APPLICATION_ERROR(-20096, 'El servicio con ID ' || p_items(i).service_id || ' no existe.');
                END;
            END IF;

            IF p_items(i).item_type = 'PART' THEN
                IF p_items(i).part_id IS NULL THEN
                    RAISE_APPLICATION_ERROR(-20097, 'Un ítem de tipo PART debe tener un ID de repuesto válido.');
                END IF;
                -- Verificar existencia de repuesto
                BEGIN
                    SELECT 1 INTO v_dummy FROM TBL_PARTS WHERE part_id = p_items(i).part_id;
                EXCEPTION
                    WHEN NO_DATA_FOUND THEN
