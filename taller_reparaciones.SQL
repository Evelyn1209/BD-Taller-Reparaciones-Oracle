-- TRIGGER: TRG_RECALC_WORKORDER_TOTAL (COMPOUND)
-- Recalcula automaticamente el total_amount de la orden cuando cambian sus items.
-- Se usa COMPOUND trigger para evitar ORA-04091 (mutating table):
--   AFTER EACH ROW : solo guarda el workorder_id afectado en memoria
--   AFTER STATEMENT: cuando ya no hay tablas mutando, ejecuta el recalculo real
CREATE OR REPLACE TRIGGER TRG_RECALC_WORKORDER_TOTAL
FOR INSERT OR UPDATE OR DELETE ON TBL_WORKORDER_ITEMS_P
COMPOUND TRIGGER

    -- Coleccion para acumular workorder_ids afectados durante el statement
    TYPE t_id_list IS TABLE OF NUMBER INDEX BY PLS_INTEGER;
    v_ids t_id_list;
    v_idx PLS_INTEGER := 0;

    -- FASE 1: capturar el workorder_id de cada fila afectada
    AFTER EACH ROW IS
    BEGIN
        v_idx := v_idx + 1;
        IF DELETING THEN
            v_ids(v_idx) := :OLD.workorder_id;
        ELSE
            v_ids(v_idx) := :NEW.workorder_id;
        END IF;
    END AFTER EACH ROW;

    -- FASE 2: recalcular totales una vez terminado el statement completo
    -- En este punto TBL_WORKORDER_ITEMS_P ya NO esta mutando
    AFTER STATEMENT IS
        v_labor   TBL_WORKORDERS_P.labor_cost%TYPE;
        v_discount TBL_WORKORDERS_P.discount_amt%TYPE;
    BEGIN
        FOR i IN 1 .. v_idx LOOP
            BEGIN
                -- Leer labor/discount ANTES del UPDATE (tabla no mutando en AFTER STATEMENT)
                SELECT NVL(labor_cost, 0), NVL(discount_amt, 0)
                INTO v_labor, v_discount
                FROM TBL_WORKORDERS_P
                WHERE workorder_id = v_ids(i);

                -- Actualizar total pasando los valores como parametros (sin leer TBL_WORKORDERS_P dentro del UPDATE)
                UPDATE TBL_WORKORDERS_P
                SET total_amount = FN_CALC_WORKORDER_TOTAL(v_ids(i), v_labor, v_discount)
                WHERE workorder_id = v_ids(i);
            EXCEPTION
                WHEN OTHERS THEN NULL;
            END;
        END LOOP;
    END AFTER STATEMENT;

END TRG_RECALC_WORKORDER_TOTAL;
/

-- TRIGGER: TRG_STOCK_WORKORDER_ITEMS
-- Controla el stock de TBL_PARTS automaticamente cuando se agregan,
-- modifican o eliminan repuestos (PART) de una orden de trabajo.
--   INSERT: valida disponibilidad y descuenta stock
--   DELETE: devuelve el stock al cancelar/quitar el item
--   UPDATE: ajusta la diferencia de cantidad o cambia de repuesto
CREATE OR REPLACE TRIGGER TRG_STOCK_WORKORDER_ITEMS
BEFORE INSERT OR UPDATE OR DELETE ON TBL_WORKORDER_ITEMS_P
FOR EACH ROW
DECLARE
    v_stock_actual TBL_PARTS.stock_qty%TYPE;
BEGIN
    -- === INSERT: nuevo item de tipo PART ===
    IF INSERTING AND :NEW.item_type = 'PART' THEN
        SELECT stock_qty INTO v_stock_actual
        FROM TBL_PARTS WHERE part_id = :NEW.part_id;

        IF v_stock_actual < :NEW.qty THEN
            RAISE_APPLICATION_ERROR(-20200,
                'Stock insuficiente para el repuesto ID ' || :NEW.part_id ||
                '. Disponible: ' || v_stock_actual || ', Solicitado: ' || :NEW.qty);
        END IF;

        UPDATE TBL_PARTS
        SET stock_qty = stock_qty - :NEW.qty
        WHERE part_id = :NEW.part_id;

    -- === DELETE: item de tipo PART eliminado, devolver stock ===
    ELSIF DELETING AND :OLD.item_type = 'PART' THEN
        UPDATE TBL_PARTS
        SET stock_qty = stock_qty + :OLD.qty
        WHERE part_id = :OLD.part_id;

    -- === UPDATE: cambio de cantidad o de repuesto ===
    ELSIF UPDATING AND :NEW.item_type = 'PART' THEN
        -- Si cambia el repuesto: devolver stock del antiguo
        IF NVL(:OLD.part_id, -1) <> NVL(:NEW.part_id, -1) THEN
            IF :OLD.part_id IS NOT NULL THEN
                UPDATE TBL_PARTS SET stock_qty = stock_qty + :OLD.qty WHERE part_id = :OLD.part_id;
            END IF;
            -- Validar y descontar el nuevo
            SELECT stock_qty INTO v_stock_actual FROM TBL_PARTS WHERE part_id = :NEW.part_id;
            IF v_stock_actual < :NEW.qty THEN
                RAISE_APPLICATION_ERROR(-20201,
                    'Stock insuficiente para el repuesto ID ' || :NEW.part_id ||
                    '. Disponible: ' || v_stock_actual || ', Solicitado: ' || :NEW.qty);
            END IF;
            UPDATE TBL_PARTS SET stock_qty = stock_qty - :NEW.qty WHERE part_id = :NEW.part_id;
        -- Si solo cambia la cantidad: ajustar la diferencia
        ELSIF :OLD.qty <> :NEW.qty THEN
            DECLARE v_diff NUMBER := :NEW.qty - :OLD.qty;
            BEGIN
                IF v_diff > 0 THEN
                    SELECT stock_qty INTO v_stock_actual FROM TBL_PARTS WHERE part_id = :NEW.part_id;
                    IF v_stock_actual < v_diff THEN
                        RAISE_APPLICATION_ERROR(-20202,
                            'Stock insuficiente para aumentar la cantidad del repuesto ID ' || :NEW.part_id ||
                            '. Disponible: ' || v_stock_actual || ', Adicional requerido: ' || v_diff);
                    END IF;
                END IF;
                UPDATE TBL_PARTS SET stock_qty = stock_qty - v_diff WHERE part_id = :NEW.part_id;
            END;
        END IF;
    END IF;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20203, 'El repuesto especificado no existe en inventario.');
END TRG_STOCK_WORKORDER_ITEMS;
/

-- TRIGGER: TRG_VALIDATE_WORKORDER_STATUS
-- Impide cambios de estado invalidos en las ordenes de trabajo.
-- Regla: ENTREGADO y CANCELADO son estados finales, no se puede
-- cambiar el estado de una orden que ya llego a esos estados.
CREATE OR REPLACE TRIGGER TRG_VALIDATE_WORKORDER_STATUS
BEFORE UPDATE OF status_id ON TBL_WORKORDERS_P
FOR EACH ROW
DECLARE
    v_old_status_name TBL_WORKORDER_STATUS.name%TYPE;
BEGIN
    -- Solo aplicar si realmente cambia el status_id
    IF :OLD.status_id <> :NEW.status_id THEN
        SELECT name INTO v_old_status_name
        FROM TBL_WORKORDER_STATUS
        WHERE status_id = :OLD.status_id;

        -- Estados finales: no se puede cambiar desde ENTREGADO o CANCELADO
        IF UPPER(v_old_status_name) IN ('ENTREGADO', 'CANCELADO') THEN
            RAISE_APPLICATION_ERROR(-20210,
                'La orden #' || :OLD.workorder_id ||
                ' tiene estado final "' || v_old_status_name ||
                '" y no puede ser modificada.');
        END IF;
    END IF;
EXCEPTION
    WHEN NO_DATA_FOUND THEN NULL;
END TRG_VALIDATE_WORKORDER_STATUS;
/

