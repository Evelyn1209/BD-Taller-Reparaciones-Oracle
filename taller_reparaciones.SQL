-- TBL_IDENTIFICATION_TYPE (READ IS THE ONLY PART OF THE CRUD THAT WE ARE GOING TO USE IN TBL_IDENTIFICATION_TYPE )
-- READ IDENTIFICATION_TYPE BY ID
CREATE OR REPLACE PROCEDURE SP_READ_IDENTIFICATION_TYPE_BY_ID (
    IT_IDENTIFICATION_TYPE_ID IN  TBL_IDENTIFICATION_TYPE.IDENTIFICATION_TYPE_ID%TYPE,
    IT_NAME                  OUT TBL_IDENTIFICATION_TYPE.NAME%TYPE
)
AS
BEGIN
    SELECT NAME
    INTO IT_NAME
    FROM TBL_IDENTIFICATION_TYPE
    WHERE IDENTIFICATION_TYPE_ID = IT_IDENTIFICATION_TYPE_ID;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(
            -20007,
            'ERROR: No existe un tipo de identificacion con ese id.'
        );
    WHEN TOO_MANY_ROWS THEN
        RAISE_APPLICATION_ERROR(
            -20008,
            'ERROR: Datos duplicados para este id.'
        );
    WHEN OTHERS THEN
        RAISE_APPLICATION_ERROR(
            -20009,
            'ERROR al consultar tipo de identificacion: ' || SQLERRM
        );
END;
/
