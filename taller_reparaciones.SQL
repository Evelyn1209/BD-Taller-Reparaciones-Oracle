-- CREATE USER
CREATE OR REPLACE PROCEDURE SP_CREATE_USER (
    p_identification_number IN TBL_PERSON.identification_number%TYPE,
    p_username              IN TBL_SYS_USERS.username%TYPE,
    p_password_hash         IN TBL_SYS_USERS.password_hash%TYPE,
    p_is_admin              IN TBL_SYS_USERS.is_admin%TYPE,
    p_response              OUT NUMBER
) AS
    v_person_id   NUMBER;
    v_employee_id NUMBER;
BEGIN
    -- 1. Buscar la persona por identificación
    v_person_id := FN_GET_PERSON(p_identification_number);
    
    IF v_person_id = 0 THEN
        RAISE_APPLICATION_ERROR(-20110, 'La persona con identificación ' || p_identification_number || ' no existe en el sistema.');
    END IF;

    -- 2. Validar que la persona sea un empleado
    v_employee_id := FN_GET_EMPLOYEE(v_person_id);
    
    IF v_employee_id = 0 THEN
        RAISE_APPLICATION_ERROR(-20111, 'Solo los empleados pueden tener un usuario en el sistema.');
    END IF;

    -- 3. Insertar el usuario
    INSERT INTO TBL_SYS_USERS (person_id, username, password_hash, is_admin, status)
    VALUES (v_person_id, p_username, p_password_hash, NVL(p_is_admin, 'N'), 'ACTIVE');

    DBMS_OUTPUT.PUT_LINE('Éxito: Usuario "' || p_username || '" creado correctamente para el empleado.');
