CREATE TABLE TBL_WORKORDER_ITEMS_P (
  item_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workorder_id  NUMBER NOT NULL,
  item_type     VARCHAR2(10) NOT NULL CHECK (item_type IN ('SERVICE','PART')),
  service_id    NUMBER,
  part_id       NUMBER,
  qty           NUMBER(10,2) DEFAULT 1 CHECK (qty > 0),
  unit_price    NUMBER(10,2) NOT NULL CHECK (unit_price >= 0),
  CONSTRAINT fk_item_wo FOREIGN KEY (workorder_id) REFERENCES TBL_WORKORDERS_P(workorder_id),
  CONSTRAINT fk_item_service FOREIGN KEY (service_id) REFERENCES TBL_SERVICES(service_id),
  CONSTRAINT fk_item_part FOREIGN KEY (part_id) REFERENCES TBL_PARTS(part_id),
  CONSTRAINT ck_item_refs CHECK (
      (item_type='SERVICE' AND service_id IS NOT NULL AND part_id IS NULL)
   OR (item_type='PART' AND part_id IS NOT NULL AND service_id IS NULL)
  )
)
PARTITION BY HASH(workorder_id)
PARTITIONS 4;
